const dictionaries: Record<Lang, Record<MessageKey, string>> = { tr, en }

export type Vars = Record<string, string | number>

export function translate(lang: Lang, key: MessageKey, vars?: Vars): string {
  let text: string = dictionaries[lang][key] ?? dictionaries.tr[key] ?? key
  // "one|other" plural forms, chosen by the `n` variable (English only; Turkish
  // nouns stay singular after a number).
  if (text.includes('|')) {
    const [one, other] = text.split('|')
    text = vars?.n === 1 ? one : other
  }
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, formatValue(lang, value))
    }
  }
  return text
}

function formatValue(lang: Lang, value: string | number): string {
  return typeof value === 'number' ? formatNumber(lang, value) : value
}

export function formatNumber(lang: Lang, value: number): string {
  return new Intl.NumberFormat(lang === 'tr' ? 'tr-TR' : 'en-US').format(value)
}

export function formatBytes(lang: Lang, bytes: number): string {
  const units = ['B', 'KB', 'MB', 'GB']
  let value = bytes
  let unit = 0
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024
    unit++
  }
  const digits = unit === 0 || value >= 100 ? 0 : 1
  const formatted = new Intl.NumberFormat(lang === 'tr' ? 'tr-TR' : 'en-US', {
    maximumFractionDigits: digits,
    minimumFractionDigits: digits,
  }).format(value)
  return `${formatted} ${units[unit]}`
}

export function systemLang(locale: string): Lang {
  return locale.toLowerCase().startsWith('tr') ? 'tr' : 'en'
}

